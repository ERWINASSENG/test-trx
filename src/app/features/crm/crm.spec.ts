      title: 'Transit Aérien Pièces Urgentes',
      stage: 'won',
      transportMode: 'air',
      direction: 'import',
      origin: 'Paris CDG',
      destination: 'Douala DLA',
      goodsDescription: 'Électronique médicale',
      weightKg: 350,
      volumeM3: 2.5,
      incoterm: 'CIP',
      estimatedValue: 6200000,
      currency: 'XAF',
      expectedCloseDate: '2026-10-20',
